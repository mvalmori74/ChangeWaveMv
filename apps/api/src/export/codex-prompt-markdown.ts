/**
 * The obligations the generated prompt places on the coding agent.
 *
 * These are appended by the platform rather than written by the model, so every
 * exported prompt carries them verbatim whatever the model decided to say.
 */
export const CODEX_EXECUTION_RULES = `
## EXECUTION RULES (mandatory)

1. Analyse the repository before writing code. State what you found.
2. Produce a written plan and follow it. Update it when reality disagrees.
3. Implement in phases. Each phase must leave the build compiling.
4. Run the test suite after each phase. Do not proceed on a red build.
5. Fix the errors you introduce. Do not work around them by deleting tests.
6. Never invent an API, SDK, endpoint or library that you have not verified
   exists. If a capability is missing, stop and say so.
7. Leave no critical TODO. A TODO is acceptable only for an explicitly
   out-of-scope item, and it must be listed in the README.
8. Keep the code compilable and the repository in a runnable state at all times.
9. Document non-obvious decisions in the code or in docs/, briefly.
10. Deliver a complete README: what it is, how to install, run, test and build.

## WHAT "DONE" MEANS

- The application builds from a clean checkout.
- The documented run command starts it.
- The test suite passes.
- Every acceptance criterion above is demonstrably met.
- Nothing in the repository contains a secret, a token or a password.
`.trim();


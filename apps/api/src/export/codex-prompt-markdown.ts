export function renderCodexPromptMarkdown(
  output: PromptEngineerOutput,
  meta: { generatedAt: Date; opportunityTitle: string; synthetic: boolean },
): string {
  const lines: string[] = [];
  const push = (...values: string[]) => lines.push(...values);

  push(`# Build prompt — ${output.projectName}`, '');
  push(
    'You are a senior software engineer working autonomously in a code',
    'generation agent. Build the application specified below, end to end.',
    '',
  );

  if (meta.synthetic) {
    push(
      '> **Warning:** generated with the offline mock provider. The sections',
      '> below are placeholders, not a real specification.',
      '',
    );
  }

  push('## STACK', '');
  push(`- **Platform:** ${output.stack.platform}`);
  push(`- **Language:** ${output.stack.language}`);
  push(`- **Frameworks:** ${output.stack.frameworks.join(', ') || 'implementer choice'}`);
  push(`- **Database:** ${output.stack.database}`);
  push(`- **Infrastructure:** ${output.stack.infrastructure}`);
  push('');

  push('## REPOSITORY STRUCTURE', '', '```');
  for (const entry of output.repositoryLayout) push(entry);
  push('```', '');

  for (const section of PROMPT_SECTIONS) {
    push(`## ${SECTION_TITLES[section]}`, '', output.sections[section], '');
  }

  push(CODEX_EXECUTION_RULES, '');
  push('---', '');
  push(
    `_Generated by AI App Factory on ${meta.generatedAt.toISOString()} from the PRD for ` +
      `"${meta.opportunityTitle}"._`,
  );

  return lines.join('\n');
}

/** Rough token count, used to warn when a prompt is getting unwieldy. */
export function estimatePromptTokens(markdown: string): number {
  return Math.ceil(markdown.length / 4);
}
